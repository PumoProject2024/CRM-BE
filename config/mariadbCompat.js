const { DataTypes, Model, QueryTypes } = require('sequelize');

/**
 * MariaDB compatibility hooks for the shared Sequelize instance.
 *
 * 1. beforeDefine  -> every DATE column (and the createdAt/updatedAt timestamps) becomes
 *                     DATETIME(6). PostgreSQL timestamptz kept microsecond precision; Sequelize's
 *                     default DATE maps to DATETIME with whole seconds, which would make rows
 *                     created in the same second sort non-deterministically.
 *
 * 2. afterFind     -> MariaDB stores JSON as LONGTEXT and the mysql2 driver does not parse it, and
 *                     Sequelize's mysql dialect registers no JSON parser. Result: JSON columns come
 *                     back as strings. This hook parses them so the application keeps receiving
 *                     objects/arrays exactly as it did from PostgreSQL. It is only active when the
 *                     server reports itself as MariaDB (MySQL 8 already returns parsed JSON, and
 *                     parsing again would corrupt legitimate JSON string values).
 */

const DATE_PRECISION = 6;

// ---------------------------------------------------------------------------------------------
// DATETIME(6)
// ---------------------------------------------------------------------------------------------

const isUnsizedDate = (type) =>
  type === DataTypes.DATE ||
  (type instanceof DataTypes.DATE && !type._length && !(type.options && type.options.length));

const applyDatetimePrecision = (attributes, options) => {
  for (const name of Object.keys(attributes)) {
    const attr = attributes[name];
    if (attr === DataTypes.DATE) {
      attributes[name] = { type: DataTypes.DATE(DATE_PRECISION) };
    } else if (attr && typeof attr === 'object' && isUnsizedDate(attr.type)) {
      attr.type = DataTypes.DATE(DATE_PRECISION);
    }
  }

  // Sequelize adds createdAt/updatedAt itself (as plain DATE) unless the attribute already exists,
  // so declare them here with the wider precision. Mirror Sequelize's own definition, including
  // _autoGenerated, so validation treats them exactly as it treats the built-in ones.
  if (options.timestamps === false) return;
  const timestampName = (option, fallback) =>
    option === false ? null : (typeof option === 'string' ? option : fallback);
  for (const name of [
    timestampName(options.createdAt, 'createdAt'),
    timestampName(options.updatedAt, 'updatedAt'),
  ]) {
    if (name && !(name in attributes)) {
      attributes[name] = {
        type: DataTypes.DATE(DATE_PRECISION),
        allowNull: false,
        _autoGenerated: true,
      };
    }
  }
};

// ---------------------------------------------------------------------------------------------
// JSON parsing on MariaDB
// ---------------------------------------------------------------------------------------------

const jsonAttributeCache = new WeakMap();

const jsonAttributeNames = (model) => {
  if (!model || !model.rawAttributes) return [];
  if (!jsonAttributeCache.has(model)) {
    const names = Object.keys(model.rawAttributes).filter((name) => {
      const type = model.rawAttributes[name].type;
      return type && (type.key || (type.constructor && type.constructor.key)) === 'JSON';
    });
    jsonAttributeCache.set(model, names);
  }
  return jsonAttributeCache.get(model);
};

const parseValue = (value, where) => {
  if (typeof value !== 'string') return value;
  try {
    return JSON.parse(value);
  } catch (error) {
    // Never swallow silently: leave the raw string in place and say so.
    console.warn(`[mariadbCompat] Could not JSON.parse ${where}: ${error.message}`);
    return value;
  }
};

const parseInstance = (instance) => {
  const model = instance.constructor;
  for (const name of jsonAttributeNames(model)) {
    const current = instance.dataValues[name];
    if (typeof current === 'string') {
      const parsed = parseValue(current, `${model.name}.${name}`);
      instance.dataValues[name] = parsed;
      // Keep the "previous" snapshot identical so the row is not reported as changed.
      if (instance._previousDataValues) instance._previousDataValues[name] = parsed;
    }
  }
  // Included (joined) models.
  for (const value of Object.values(instance.dataValues)) {
    if (value instanceof Model) {
      parseInstance(value);
    } else if (Array.isArray(value)) {
      for (const item of value) if (item instanceof Model) parseInstance(item);
    }
  }
};

const parseRawRow = (row, model) => {
  for (const name of jsonAttributeNames(model)) {
    if (row && typeof row[name] === 'string') row[name] = parseValue(row[name], `${model.name}.${name}`);
  }
};

/** Parses JSON-typed attributes in a find* result (instance, array of instances, or raw rows). */
const parseJsonResult = (result, options = {}) => {
  if (result === null || result === undefined) return;
  const rows = Array.isArray(result) ? result : [result];
  for (const row of rows) {
    if (row instanceof Model) parseInstance(row);
    else if (row && typeof row === 'object' && options.raw) parseRawRow(row, options.model);
  }
};

// ---------------------------------------------------------------------------------------------
// Installation
// ---------------------------------------------------------------------------------------------

/**
 * @param {import('sequelize').Sequelize} sequelize
 * @param {{ forceJsonParse?: boolean }} [settings] forceJsonParse: skip server detection (tests).
 */
const installMariaDbCompat = (sequelize, settings = {}) => {
  sequelize.addHook('beforeDefine', applyDatetimePrecision);

  let serverIsMariaDb = null; // cached promise
  const detectMariaDb = () => {
    if (typeof settings.forceJsonParse === 'boolean') return Promise.resolve(settings.forceJsonParse);
    if (!serverIsMariaDb) {
      serverIsMariaDb = sequelize
        .query('SELECT VERSION() AS version', { type: QueryTypes.SELECT })
        .then((rows) => /mariadb/i.test(String(rows[0] && rows[0].version)))
        .catch((error) => {
          serverIsMariaDb = null; // do not cache a failure; the find itself fails loudly
          throw error;
        });
    }
    return serverIsMariaDb;
  };

  // Regular function on purpose: Sequelize runs model hooks with `this` bound to the Model class, and
  // (unlike the query options) that is the only place the model is available for raw:true results.
  sequelize.addHook('afterFind', async function parseJsonAfterFind(result, options) {
    if (result === null || result === undefined) return;
    if (await detectMariaDb()) parseJsonResult(result, { ...options, model: (options && options.model) || this });
  });
};

module.exports = installMariaDbCompat;
module.exports.parseJsonResult = parseJsonResult;
module.exports.applyDatetimePrecision = applyDatetimePrecision;
